import pandas as pd


def generate_sales_tasks(result_df):
    """
    根据AI客户分析结果，
    自动生成销售跟进任务。
    """

    tasks = []

    for _, row in result_df.iterrows():

        score = row["客户评分"]
        priority = row["客户优先级"]

        # ==============================
        # 高优先级客户
        # ==============================

        if priority == "高":

            task = {
                "公司": row["公司"],
                "国家": row["国家"],
                "客户评分": score,
                "优先级": "高",
                "任务": "立即发送开发邮件",
                "建议时间": "今天",
                "原因": "客户评分较高，具备较高开发价值",
                "跟进方式": "邮件 + 人工跟进",
                "状态": "待处理"
            }

        # ==============================
        # 中优先级客户
        # ==============================

        elif priority == "中":

            task = {
                "公司": row["公司"],
                "国家": row["国家"],
                "客户评分": score,
                "优先级": "中",
                "任务": "进一步了解客户需求",
                "建议时间": "3天内",
                "原因": "客户存在潜在价值，但需要进一步确认需求",
                "跟进方式": "邮件",
                "状态": "待处理"
            }

        # ==============================
        # 低优先级客户
        # ==============================

        else:

            task = {
                "公司": row["公司"],
                "国家": row["国家"],
                "客户评分": score,
                "优先级": "低",
                "任务": "暂缓开发",
                "建议时间": "7天后重新评估",
                "原因": "当前客户评分较低",
                "跟进方式": "暂不联系",
                "状态": "待处理"
            }

        tasks.append(task)

    task_df = pd.DataFrame(tasks)

    # ==============================
    # 按客户评分从高到低排序
    # ==============================

    task_df = task_df.sort_values(
        by="客户评分",
        ascending=False
    )

    return task_df